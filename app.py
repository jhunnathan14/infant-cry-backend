import os
import numpy as np
import librosa
import tensorflow as tf
from fastapi import FastAPI, UploadFile, File
from fastapi.middleware.cors import CORSMiddleware

app = FastAPI()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

MODEL_PATH = "infant_cry_pathology_int8.tflite"
interpreter = tf.lite.Interpreter(model_path=MODEL_PATH)
interpreter.allocate_tensors()

input_details = interpreter.get_input_details()
output_details = interpreter.get_output_details()
input_scale, input_zero_point = input_details[0]['quantization']
output_scale, output_zero_point = output_details[0]['quantization']

@app.post("/predict")
async def predict_cry(file: UploadFile = File(...)):
    temp_path = f"temp_{file.filename}"
    with open(temp_path, "wb") as buffer:
        buffer.write(await file.read())

    try:
        SR, DURATION = 16000, 3.0
        y, _ = librosa.load(temp_path, sr=SR, duration=DURATION)
        target_len = int(SR * DURATION)
        if len(y) < target_len:
            y = np.pad(y, (0, target_len - len(y)), mode='constant')
        else:
            y = y[:target_len]

        mel_spec = librosa.feature.melspectrogram(y=y, sr=SR, n_fft=2048, hop_length=512, n_mels=64)
        log_mel_spec = librosa.power_to_db(mel_spec, ref=np.max)
        norm_spec = (log_mel_spec - log_mel_spec.min()) / (log_mel_spec.max() - log_mel_spec.min() + 1e-6)
        input_data = np.expand_dims(norm_spec, axis=(0, -1)).astype(np.float32)

        if input_details[0]['dtype'] == np.int8:
            input_data = (input_data / input_scale + input_zero_point).astype(np.int8)

        interpreter.set_tensor(input_details[0]['index'], input_data)
        interpreter.invoke()
        output_data = interpreter.get_tensor(output_details[0]['index'])

        if output_details[0]['dtype'] == np.int8:
            score = float(((output_data.astype(np.float32) - output_zero_point) * output_scale).squeeze())
        else:
            score = float(output_data[0][0])

        label = "Pathological" if score >= 0.5 else "Physiological"
        confidence = score if label == "Pathological" else (1.0 - score)

        return {
            "classification": label,
            "confidence": round(confidence * 100, 2),
            "raw_score": round(score, 4)
        }
    finally:
        if os.path.exists(temp_path):
            os.remove(temp_path)