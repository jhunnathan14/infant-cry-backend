from fastapi import FastAPI, UploadFile, File, HTTPException
from fastapi.middleware.cors import CORSMiddleware
import numpy as np
import librosa
import io
import time
import os
import traceback
import tensorflow as tf

app = FastAPI(title="Infant Cry Classification API")

# Enable CORS for your Hostinger frontend and local testing
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Allows requests from any origin
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Robust path resolution for Render and local execution
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "infant_cry_pathology_int8.tflite")

try:
    interpreter = tf.lite.Interpreter(model_path=MODEL_PATH)
    interpreter.allocate_tensors()
    input_details = interpreter.get_input_details()
    output_details = interpreter.get_output_details()
    print("TFLite Model loaded successfully.")
except Exception as e:
    print(f"Error loading TFLite model: {e}")

@app.get("/")
def home():
    return {"status": "Online", "message": "Infant Cry Classification Backend is running."}

@app.post("/predict")
async def predict_cry(file: UploadFile = File(...)):
    start_time = time.time()

    try:
        # Read uploaded audio file bytes
        contents = await file.read()
        audio_file = io.BytesIO(contents)

        # Load audio using librosa (resample to 16kHz standard)
        y, sr = librosa.load(audio_file, sr=16000)

        # Extract Log-Mel Spectrogram
        mel_spectrogram = librosa.feature.melspectrogram(y=y, sr=sr, n_mels=64, n_fft=2048, hop_length=512)
        log_mel_spec = librosa.power_to_db(mel_spectrogram, ref=np.max)

        # Normalize or pad/truncate to match model input shape requirement
        expected_frames = input_details[0]['shape'][2]

        if log_mel_spec.shape[1] < expected_frames:
            pad_width = expected_frames - log_mel_spec.shape[1]
            log_mel_spec = np.pad(log_mel_spec, ((0, 0), (0, pad_width)), mode='constant')
        else:
            log_mel_spec = log_mel_spec[:, :expected_frames]

        # Reshape to match model input tensor
        input_data = np.expand_dims(log_mel_spec, axis=-1)
        input_data = np.expand_dims(input_data, axis=0)

        # Handle INT8 quantization input scaling if applicable
        if input_details[0]['dtype'] == np.int8:
            input_scale, input_zero_point = input_details[0]['quantization']
            if input_scale > 0:
                input_data = np.round(input_data / input_scale + input_zero_point).astype(np.int8)
            else:
                input_data = input_data.astype(np.int8)
        else:
            input_data = input_data.astype(np.float32)

        # Set tensor and invoke interpreter
        interpreter.set_tensor(input_details[0]['index'], input_data)
        interpreter.invoke()

        # Get output prediction tensor
        output_data = interpreter.get_tensor(output_details[0]['index'])

        # Handle INT8 quantization output dequantization if applicable
        if output_details[0]['dtype'] == np.int8:
            output_scale, output_zero_point = output_details[0]['quantization']
            output_data = (output_data.astype(np.float32) - output_zero_point) * output_scale

        # Process probabilities / classification outcome
        prediction_idx = int(np.argmax(output_data[0]))
        confidence = float(np.max(tf.nn.softmax(output_data[0]) if output_data.shape[-1] > 1 else tf.sigmoid(output_data[0])))

        labels = ["Pathological", "Physiological"]
        predicted_label = labels[prediction_idx] if prediction_idx < len(labels) else "Unknown"

        latency_ms = (time.time() - start_time) * 1000

        return {
            "prediction": predicted_label,
            "confidence": confidence,
            "latency_ms": latency_ms
        }

    except Exception as e:
        # This will print the full error traceback to your Render logs
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))